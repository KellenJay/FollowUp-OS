"""Uploads real-production eval results (from run-live.ts, grading actual
threads/followups/meetings pulled from Supabase, not synthetic test cases)
into Azure AI Foundry's classic Evaluation view -- same mechanism as
foundry_upload.py, separate run names so golden and live results sit side
by side in the same Evaluations list, distinguishable by name
("{decision_point}-golden-eval" vs "{decision_point}-live-eval-<date>").

Prerequisites: same as foundry_upload.py, plus
results/followup-os-live-eval-results.json already generated by
`npm run eval:live`.
"""

import json
import os
from datetime import datetime, timezone

from azure.identity import DefaultAzureCredential
from foundry_common import SCRIPT_DIR, normalize, upload_decision_point

RESULTS_PATH = SCRIPT_DIR / "results" / "followup-os-live-eval-results.json"


def build_dataset_row(row: dict, dimension_ids: list[str]) -> dict:
    dataset_row = {
        "row_ref": row["ref"],
        "candidate_input": json.dumps(row["candidate_input"]),
        "candidate_output": json.dumps(row["candidate_output"]),
        "reasoning": row["reasoning"],
        "total_score": normalize(row["actual_score"]),
    }
    for dim_id in dimension_ids:
        dataset_row[f"{dim_id}_score"] = normalize(row["dimension_scores"][dim_id])
    return dataset_row


def main():
    project_endpoint = os.environ.get("AZURE_AI_FOUNDRY_PROJECT_ENDPOINT")
    if not project_endpoint:
        raise SystemExit(
            "AZURE_AI_FOUNDRY_PROJECT_ENDPOINT is not set. Add it to .env.local "
            "once the Foundry project exists (Foundry portal -> Project details -> Overview)."
        )

    if not RESULTS_PATH.exists():
        raise SystemExit(f"{RESULTS_PATH} not found. Run `npm run eval:live` first to generate it.")

    DefaultAzureCredential().get_token("https://management.azure.com/.default")

    with open(RESULTS_PATH, "r", encoding="utf-8") as f:
        results = json.load(f)

    run_date = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M")

    for decision_point in results["decision_points"]:
        if not decision_point["rows"]:
            print(f"\n=== {decision_point['id']}: no real rows sampled, skipping ===")
            continue
        dimension_ids = [d["id"] for d in decision_point["dimensions"]]
        rows = [build_dataset_row(r, dimension_ids) for r in decision_point["rows"]]
        upload_decision_point(decision_point, project_endpoint, rows, f"{decision_point['id']}-live-eval-{run_date}")

    print("\nDone. Check the Foundry portal's Evaluation view (classic — toggle 'New Foundry' off) to confirm the runs appear.")


if __name__ == "__main__":
    main()
