"""Uploads the existing golden-dataset eval results into Azure AI Foundry's
Evaluation view, so the same scores that already live in
results/followup-os-eval-results.json (produced by run-golden.ts's
Claude-judge grading) are also visible there.

Deliberately does NOT re-grade anything — grading stays in TypeScript
(grade.ts), which already works and is calibrated against Claude as an
independent judge. This script is a thin adapter: read the existing scores,
reshape them into what the Azure AI Evaluation SDK expects, and register
one passthrough "evaluator" per rubric dimension that just echoes the score
already computed, so Foundry becomes a second place to view the same
trusted results rather than a second grader.

One evaluate() run per decision_point (classify_and_draft,
followup_relevance, transcript_summary, fallback_followup), since each has
its own distinct set of rubric dimensions.

Prerequisites (see the plan doc / Ellen's own setup):
  - A Foundry project already created in https://ai.azure.com
  - AZURE_AI_FOUNDRY_PROJECT_ENDPOINT set in .env.local (the project's
    endpoint, from Foundry portal -> Project details -> Overview)
  - Azure credentials available to azure-identity's DefaultAzureCredential
    (e.g. already logged in via `az login`, or a service principal's
    env vars) -- NOT a raw API key typed into this script.
  - `pip install -r requirements.txt` (azure-ai-evaluation, azure-identity)
  - results/followup-os-eval-results.json already generated by
    `npx tsx scripts/eval/run-golden.ts`

NOTE: the Azure AI Evaluation SDK is a fast-moving, actively-changing
surface (Foundry has both "classic" and "new" project shapes as of writing,
with different connection conventions). This is built against the
documented evaluate()/custom-evaluator pattern, but the exact
azure_ai_project connection shape may need a small adjustment the first
time it's actually run against a real project -- treat this as ready to
smoke-test, not guaranteed correct on the first try.
"""

import json
import os
from pathlib import Path

from azure.ai.evaluation import evaluate
from azure.identity import DefaultAzureCredential

SCRIPT_DIR = Path(__file__).parent
RESULTS_PATH = SCRIPT_DIR / "results" / "followup-os-eval-results.json"
DATASET_DIR = SCRIPT_DIR / "results" / "foundry_datasets"


class PassthroughEvaluator:
    """Echoes a score that was already computed by grade.ts (Claude judge)
    instead of grading anything itself -- Foundry just needs a callable
    that returns a numeric score per row for it to log as an evaluator
    column."""

    def __init__(self, dimension_id: str):
        self.dimension_id = dimension_id

    def __call__(self, *, score: float, **kwargs) -> dict:
        return {self.dimension_id: score}


def normalize(score_0_to_100: float) -> float:
    """Foundry's custom-evaluator convention expects 0.0-1.0; our existing
    rubric scores are 0-100."""
    return round(score_0_to_100 / 100.0, 4)


def build_dataset_row(test_case: dict, dimension_ids: list[str]) -> dict:
    row = {
        "test_case_id": test_case["id"],
        "label": test_case["label"],
        "candidate_input": json.dumps(test_case["candidate_input"]),
        "candidate_output": json.dumps(test_case["candidate_output"]),
        "reasoning": test_case["reasoning"],
        "total_score": normalize(test_case["actual_score"]),
    }
    for dim_id in dimension_ids:
        row[f"{dim_id}_score"] = normalize(test_case["dimension_scores"][dim_id])
    return row


def upload_decision_point(decision_point: dict, project_endpoint: str):
    dp_id = decision_point["id"]
    dimension_ids = [d["id"] for d in decision_point["dimensions"]]

    DATASET_DIR.mkdir(parents=True, exist_ok=True)
    dataset_path = DATASET_DIR / f"{dp_id}.jsonl"
    with open(dataset_path, "w", encoding="utf-8") as f:
        for tc in decision_point["test_cases"]:
            row = build_dataset_row(tc, dimension_ids)
            f.write(json.dumps(row) + "\n")

    evaluators = {"total_score": PassthroughEvaluator("total_score")}
    evaluator_config = {"total_score": {"column_mapping": {"score": "${data.total_score}"}}}
    for dim_id in dimension_ids:
        evaluators[dim_id] = PassthroughEvaluator(dim_id)
        evaluator_config[dim_id] = {"column_mapping": {"score": f"${{data.{dim_id}_score}}"}}

    print(f"\n=== Uploading {dp_id} ({len(decision_point['test_cases'])} test cases) ===")
    result = evaluate(
        data=str(dataset_path),
        evaluators=evaluators,
        evaluator_config=evaluator_config,
        azure_ai_project=project_endpoint,
        evaluation_name=f"{dp_id}-golden-eval",
    )
    print(f"Uploaded {dp_id} -> {result.get('studio_url', '(no studio URL returned)')}")


def main():
    project_endpoint = os.environ.get("AZURE_AI_FOUNDRY_PROJECT_ENDPOINT")
    if not project_endpoint:
        raise SystemExit(
            "AZURE_AI_FOUNDRY_PROJECT_ENDPOINT is not set. Add it to .env.local "
            "once the Foundry project exists (Foundry portal -> Project details -> Overview)."
        )

    if not RESULTS_PATH.exists():
        raise SystemExit(
            f"{RESULTS_PATH} not found. Run `npx tsx scripts/eval/run-golden.ts` first "
            "to generate it -- this script uploads existing results, it doesn't grade anything itself."
        )

    # Confirms credentials resolve before doing any work, rather than
    # failing partway through the first decision point.
    DefaultAzureCredential().get_token("https://management.azure.com/.default")

    with open(RESULTS_PATH, "r", encoding="utf-8") as f:
        results = json.load(f)

    for decision_point in results["decision_points"]:
        upload_decision_point(decision_point, project_endpoint)

    print("\nDone. Check the Foundry portal's Evaluation view to confirm the runs appear.")


if __name__ == "__main__":
    main()
