"""Uploads the existing golden-dataset (synthetic test case) eval results
into Azure AI Foundry's classic Evaluation view, so the same scores that
already live in results/followup-os-eval-results.json (produced by
run-golden.ts's Claude-judge grading) are also visible there.

For the equivalent upload of *real production* results, see
foundry_upload_live.py -- same mechanism, different source file.

Prerequisites:
  - A Foundry project already created in https://ai.azure.com
  - AZURE_AI_FOUNDRY_PROJECT_ENDPOINT set in .env.local (the project's
    endpoint, from Foundry portal -> Project details -> Overview)
  - Azure credentials available to azure-identity's DefaultAzureCredential
    (e.g. already logged in via `az login`) -- NOT a raw API key.
  - `pip install -r requirements.txt`
  - results/followup-os-eval-results.json already generated by
    `npm run eval:golden`

NOTE: confirmed working against the classic Foundry project view (toggle
"New Foundry" off) -- the new unified project experience uses a different
SDK (azure-ai-projects' AIProjectClient + openai_client.evals), not this
evaluate() call, and pushing to that isn't built yet.
"""

import json
import os

from azure.identity import DefaultAzureCredential
from foundry_common import SCRIPT_DIR, normalize, upload_decision_point

RESULTS_PATH = SCRIPT_DIR / "results" / "followup-os-eval-results.json"


def build_dataset_row(test_case: dict, dimension_ids: list[str]) -> dict:
    row = {
        "test_case_id": test_case["id"],
        "label": test_case["label"],
        "candidate_input": json.dumps(test_case["candidate_input"]),
        "candidate_output": json.dumps(test_case["candidate_output"]),
        "reasoning": test_case["reasoning"],
        "total_score": normalize(test_case["actual_score"]),
    }
    for dim_id in dimension_ids:
        row[f"{dim_id}_score"] = normalize(test_case["dimension_scores"][dim_id])
    return row


def main():
    project_endpoint = os.environ.get("AZURE_AI_FOUNDRY_PROJECT_ENDPOINT")
    if not project_endpoint:
        raise SystemExit(
            "AZURE_AI_FOUNDRY_PROJECT_ENDPOINT is not set. Add it to .env.local "
            "once the Foundry project exists (Foundry portal -> Project details -> Overview)."
        )

    if not RESULTS_PATH.exists():
        raise SystemExit(
            f"{RESULTS_PATH} not found. Run `npm run eval:golden` first "
            "to generate it -- this script uploads existing results, it doesn't grade anything itself."
        )

    # Confirms credentials resolve before doing any work, rather than
    # failing partway through the first decision point.
    DefaultAzureCredential().get_token("https://management.azure.com/.default")

    with open(RESULTS_PATH, "r", encoding="utf-8") as f:
        results = json.load(f)

    for decision_point in results["decision_points"]:
        dimension_ids = [d["id"] for d in decision_point["dimensions"]]
        rows = [build_dataset_row(tc, dimension_ids) for tc in decision_point["test_cases"]]
        upload_decision_point(decision_point, project_endpoint, rows, f"{decision_point['id']}-golden-eval")

    print("\nDone. Check the Foundry portal's Evaluation view (classic — toggle 'New Foundry' off) to confirm the runs appear.")


if __name__ == "__main__":
    main()
